async function openPhotoLightbox(photoId) {
  const meta = allPhotoMetas.find(item => item.id === photoId);
  const blobRecord = await dbGet('photoBlobs', photoId);
  if (!blobRecord || !blobRecord.displayBlob) return;

  if (activeLightboxUrl) {
    URL.revokeObjectURL(activeLightboxUrl);
    activeLightboxUrl = null;
  }

  activeLightboxUrl = URL.createObjectURL(blobRecord.displayBlob);
  const imgEl = document.getElementById('lightboxFullImg');
  const capEl = document.getElementById('lightboxCaption');

  imgEl.src = activeLightboxUrl;
  capEl.innerText = meta ? `📍 ${meta.location} • ${meta.year}年${meta.month}月 ${meta.isFavorite ? '❤️' : ''}` : '';

  document.getElementById('photoLightboxOverlay').classList.add('active');
}

