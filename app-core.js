let allPhotoMetas = [];
let activePhotoId = null;
let pendingUploadFiles = [];

async function loadPhotosToMap() {
  if (clusterGroup) clusterGroup.clearLayers();
  if (unclusteredLayer) unclusteredLayer.clearLayers();
  syncActiveMarkerLayer();

  allPhotoMetas = await dbGetAll('photoMeta');
  const targetLayer = (markerDisplayMode === 'all') ? unclusteredLayer : clusterGroup;

  for (const p of allPhotoMetas) {
    if (p.lat > 90 || p.lng < 100 || p.lng > 180) {
      const migrated = getCoordsForLocationName(p.location);
      p.lat = migrated.lat;
      p.lng = migrated.lng;
      await dbPut('photoMeta', p);
    }

    const marker = L.marker([p.lat, p.lng], {
      icon: createMarkerIcon(p.markerType || currentMarkerType),
      draggable: true
    });

    marker.on('drag', (e) => {
      const pos = e.target.getLatLng();
      const detected = detectVectorRegion(pos.lat, pos.lng);
      marker.bindTooltip(`📍 ${detected}`, { permanent: false, direction: 'top', offset: [0, -32] }).openTooltip();
    });

    marker.on('dragend', async (e) => {
      marker.closeTooltip();
      marker.unbindTooltip();
      const newPos = e.target.getLatLng();
      p.lat = newPos.lat;
      p.lng = newPos.lng;
      p.location = detectVectorRegion(newPos.lat, newPos.lng);
      await dbPut('photoMeta', p);
      bindMarkerPopup(marker, p);
      marker.openPopup();
    });

    bindMarkerPopup(marker, p);
    targetLayer.addLayer(marker);
  }

  if (markerDisplayMode === 'cluster' && clusterGroup && typeof clusterGroup.refreshClusters === 'function') {
    clusterGroup.refreshClusters();
  }
}

