function extractExifFrom128KBSlice(file) {
  return new Promise((resolve) => {
    const headerBlob = file.slice(0, 131072);
    // 加入 setTimeout 防護，防止損毀圖片卡死
    const timeoutTimer = setTimeout(() => resolve({}), 800);
    
    EXIF.getData(headerBlob, function() {
      clearTimeout(timeoutTimer);
      const dateStr = EXIF.getTag(this, "DateTimeOriginal") || EXIF.getTag(this, "DateTime");
      const latData = EXIF.getTag(this, "GPSLatitude");
      const lngData = EXIF.getTag(this, "GPSLongitude");
      resolve({ dateStr, latData, lngData });
    });
  });
}

function canvasToOptimizedBlob(canvas, quality) {
  return new Promise((resolve) => {
    canvas.toBlob((webpBlob) => {
      if (webpBlob && webpBlob.size > 0) {
        resolve(webpBlob);
      } else {
        canvas.toBlob((jpegBlob) => resolve(jpegBlob), 'image/jpeg', quality);
      }
    }, 'image/webp', quality);
  });
}

async function decodeAndCascadeCompress(file) {
  let bitmap = null;
  let imgEl = null;
  let objUrl = null;

  try {
    if (window.createImageBitmap) {
      bitmap = await createImageBitmap(file);
    } else {
      objUrl = URL.createObjectURL(file);
      imgEl = await new Promise((res, rej) => {
        const im = new Image();
        im.onload = () => res(im);
        im.onerror = rej;
        im.src = objUrl;
      });
    }

    const srcSource = bitmap || imgEl;
    const origW = srcSource.width;
    const origH = srcSource.height;

    let dispW = origW, dispH = origH;
    const maxDisp = 1280;
    if (dispW > maxDisp || dispH > maxDisp) {
      if (dispW > dispH) {
        dispH = Math.round((dispH * maxDisp) / dispW);
        dispW = maxDisp;
      } else {
        dispW = Math.round((dispW * maxDisp) / dispH);
        dispH = maxDisp;
      }
    }

    const displayCanvas = document.createElement('canvas');
    displayCanvas.width = dispW;
    displayCanvas.height = dispH;
    const dispCtx = displayCanvas.getContext('2d');
    dispCtx.drawImage(srcSource, 0, 0, dispW, dispH);

    if (bitmap) { bitmap.close(); bitmap = null; }
    if (imgEl) { imgEl.src = ''; imgEl = null; }
    if (objUrl) { URL.revokeObjectURL(objUrl); objUrl = null; }

    let thumbW = dispW, thumbH = dispH;
    const maxThumb = 200;
    if (thumbW > maxThumb || thumbH > maxThumb) {
      if (thumbW > thumbH) {
        thumbH = Math.round((thumbH * maxThumb) / thumbW);
        thumbW = maxThumb;
      } else {
        thumbW = Math.round((thumbW * maxThumb) / thumbH);
        thumbH = maxThumb;
      }
    }

    const thumbCanvas = document.createElement('canvas');
    thumbCanvas.width = thumbW;
    thumbCanvas.height = thumbH;
    const thumbCtx = thumbCanvas.getContext('2d');
    thumbCtx.drawImage(displayCanvas, 0, 0, thumbW, thumbH);

    const displayBlob = await canvasToOptimizedBlob(displayCanvas, 0.74);
    const thumbBlob = await canvasToOptimizedBlob(thumbCanvas, 0.68);

    displayCanvas.width = 0; displayCanvas.height = 0;
    thumbCanvas.width = 0; thumbCanvas.height = 0;

    return { displayBlob, thumbBlob };
  } finally {
    if (bitmap) bitmap.close();
    if (imgEl) imgEl.src = '';
    if (objUrl) URL.revokeObjectURL(objUrl);
  }
}

