function sampleUniformLandPointInRegion(regionName) {
  const regionFeatures = parsedGeoFeatures.filter(f => f.properties.name === regionName && !f.properties.isBoundingBox);
  if (regionFeatures.length === 0) {
    const [cLat, cLng] = regionCentersMap[regionName] || [24.15, 120.67];
    return { lat: cLat, lng: cLng };
  }

  const totalArea = regionFeatures.reduce((acc, f) => acc + (f._outerMetrics.bboxArea || 1e-6), 0);
  let rWeight = Math.random() * totalArea;
  let chosenFeat = regionFeatures[0];
  for (const f of regionFeatures) {
    rWeight -= (f._outerMetrics.bboxArea || 1e-6);
    if (rWeight <= 0) {
      chosenFeat = f;
      break;
    }
  }

  const m = chosenFeat._outerMetrics;
  const rings = chosenFeat.geometry.coordinates;

  for (let attempt = 0; attempt < 120; attempt++) {
    const candLat = m.minLat + Math.random() * (m.maxLat - m.minLat);
    const candLng = m.minLng + Math.random() * (m.maxLng - m.minLng);
    if (isPointInPolygonRings(candLng, candLat, rings)) {
      return { lat: candLat, lng: candLng };
    }
  }

  const outerRing = rings[0];
  for (let attempt = 0; attempt < 40; attempt++) {
    const [vLng, vLat] = outerRing[Math.floor(Math.random() * outerRing.length)];
    const blend = 0.2 + Math.random() * 0.65;
    const candLat = m.centerLat + (vLat - m.centerLat) * blend;
    const candLng = m.centerLng + (vLng - m.centerLng) * blend;
    if (isPointInPolygonRings(candLng, candLat, rings)) {
      return { lat: candLat, lng: candLng };
    }
  }

  return { lat: m.centerLat, lng: m.centerLng };
}

function getCoordsForLocationName(name, allowedRegions = null) {
  const normalized = name ? name.replace(/台/g, '臺').trim() : '';
  const allRegionNames = Object.keys(regionCentersMap);
  const matchKey = allRegionNames.find(r => normalized && (r.includes(normalized.substring(0, 2)) || normalized.includes(r.substring(0, 2))));

  if (matchKey && regionCentersMap[matchKey]) {
    const pt = sampleUniformLandPointInRegion(matchKey);
    return {
      lat: pt.lat,
      lng: pt.lng,
      resolvedName: matchKey
    };
  }

  const pool = (Array.isArray(allowedRegions) && allowedRegions.length > 0)
    ? allowedRegions.filter(r => regionCentersMap[r])
    : allRegionNames;
  const validPool = pool.length > 0 ? pool : allRegionNames;

  const fallbackKey = validPool[noGpsDistributionIndex % validPool.length] || '臺中市';
  noGpsDistributionIndex++;

  const pt = sampleUniformLandPointInRegion(fallbackKey);
  return {
    lat: pt.lat,
    lng: pt.lng,
    resolvedName: fallbackKey
  };
}

