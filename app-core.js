function isPointInRing(lng, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const intersect = ((yi > lat) !== (yj > lat)) &&
      (lng < (xj - xi) * (lat - yi) / ((yj - yi) || 1e-12) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

function isPointInPolygonRings(lng, lat, rings) {
  if (!isPointInRing(lng, lat, rings[0])) return false;
  for (let k = 1; k < rings.length; k++) {
    if (isPointInRing(lng, lat, rings[k])) return false;
  }
  return true;
}

function isCoordinateOnLand(lat, lng) {
  for (const feat of parsedGeoFeatures) {
    if (feat.properties.isBoundingBox) continue; 
    if (isPointInPolygonRings(lng, lat, feat.geometry.coordinates)) {
      return true;
    }
  }
  return false;
}

// 新增碰撞判定機制：確保海洋生物不會穿透虛線外框
function isCoordinateColliding(lat, lng) {
  for (const feat of parsedGeoFeatures) {
    // 移除了 if (feat.properties.isBoundingBox) continue;
    if (isPointInPolygonRings(lng, lat, feat.geometry.coordinates)) {
      return true;
    }
  }
  return false;
}

function detectVectorRegion(lat, lng) {
  for (const feat of parsedGeoFeatures) {
    if (feat.properties.isBoundingBox) continue;
    if (isPointInPolygonRings(lng, lat, feat.geometry.coordinates)) {
      const rName = feat.properties.name;
      const rColor = feat.properties.color;
      updateSensorBadge(rColor, `${rName} (${lat.toFixed(3)}°N, ${lng.toFixed(3)}°E)`);
      return rName;
    }
  }
  updateSensorBadge('#86e8e4', `在海上 (${lat.toFixed(3)}°N, ${lng.toFixed(3)}°E)`);
  return '在海上';
}

