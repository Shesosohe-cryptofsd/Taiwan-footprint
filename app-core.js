function initMap() {
  map = L.map('map', {
    center: [23.75, 120.95],
    zoom: 7.5,
    minZoom: 6.5,
    maxZoom: 13,
    zoomSnap: 0.25,
    attributionControl: false
  });

  geoJsonLayer = L.geoJSON(parsedGeoFeatures, {
    style: (feature) => {
      if (feature.properties.isBoundingBox) {
        return {
          fillColor: 'transparent',
          color: '#9D9D9D',
          weight: 2,
          dashArray: '5, 5',
          opacity: 1,
          interactive: false
        };
      }
      return {
        fillColor: feature.properties.color,
        fillOpacity: 1,
        color: '#ffffff',
        weight: 2.2,
        opacity: 1,
        lineJoin: 'round'
      };
    },
    onEachFeature: (feature, layer) => {
      if (feature.properties.isBoundingBox) {
        if (layer.options) layer.options.interactive = false;
        return;
      }
      layer.on({
        mouseover: (e) => {
          const l = e.target;
          l.setStyle({ weight: 3.5, fillOpacity: 0.92 });
          updateSensorBadge(feature.properties.color, `游標預覽：${feature.properties.name}`);
        },
        mouseout: (e) => {
          geoJsonLayer.resetStyle(e.target);
        }
      });
    }
  }).addTo(map);

  renderAndStartRoamingOceanDecorations();

  map.fitBounds([[21.55, 118.0], [26.35, 122.8]]);

  clusterGroup = L.markerClusterGroup({
    maxClusterRadius: 32,
    spiderfyOnMaxZoom: true,
    showCoverageOnHover: false
  });
  unclusteredLayer = L.layerGroup();

  syncActiveMarkerLayer();
}

function syncActiveMarkerLayer() {
  if (!map || !clusterGroup || !unclusteredLayer) return;
  if (markerDisplayMode === 'all') {
    if (map.hasLayer(clusterGroup)) map.removeLayer(clusterGroup);
    if (!map.hasLayer(unclusteredLayer)) map.addLayer(unclusteredLayer);
  } else {
    if (map.hasLayer(unclusteredLayer)) map.removeLayer(unclusteredLayer);
    if (!map.hasLayer(clusterGroup)) map.addLayer(clusterGroup);
  }
}

