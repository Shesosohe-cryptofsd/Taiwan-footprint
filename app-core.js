function decodeTopoArc(topo, arcIndex) {
  const isReverse = arcIndex < 0;
  const rawArc = topo.arcs[isReverse ? ~arcIndex : arcIndex];
  const scale = topo.transform.scale;
  const translate = topo.transform.translate;

  let x = 0, y = 0;
  const coords = [];
  for (let i = 0; i < rawArc.length; i++) {
    x += rawArc[i][0];
    y += rawArc[i][1];
    const lng = x * scale[0] + translate[0];
    const lat = y * scale[1] + translate[1];
    coords.push([lng, lat]);
  }
  if (isReverse) coords.reverse();
  return coords;
}

function decodeTopoRing(topo, arcIndices) {
  let ring = [];
  arcIndices.forEach((idx, i) => {
    const seg = decodeTopoArc(topo, idx);
    if (i > 0 && seg.length > 0) seg.shift();
    ring = ring.concat(seg);
  });
  return ring;
}

function computeRingMetrics(ring) {
  let minLng = Infinity, maxLng = -Infinity, minLat = Infinity, maxLat = -Infinity;
  let sumLng = 0, sumLat = 0;
  ring.forEach(([lng, lat]) => {
    if (lng < minLng) minLng = lng;
    if (lng > maxLng) maxLng = lng;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
    sumLng += lng;
    sumLat += lat;
  });
  const count = ring.length || 1;
  const bboxArea = (maxLng - minLng) * (maxLat - minLat);
  return {
    centerLat: sumLat / count,
    centerLng: sumLng / count,
    minLat,
    maxLat,
    minLng,
    maxLng,
    bboxArea
  };
}

// 根據中心點與縮放倍率對多邊形陣列進行幾何轉換
function transformPolygon(rings, oldCenter, newCenter, scale) {
  return rings.map(ring => ring.map(pt => [
    (pt[0] - oldCenter[0]) * scale + newCenter[0],
    (pt[1] - oldCenter[1]) * scale + newCenter[1]
  ]));
}

async function loadAndParseTopoJSON() {
  let topoData = EMBEDDED_TAIWAN_TOPOJSON;

  parsedGeoFeatures = [];
  regionCentersMap = {};
  const largestAreaPerRegion = {};
  const regionPolygons = {};

  const geometries = topoData.objects.map.geometries;

  geometries.forEach(geom => {
    const baseName = geom.properties.name;
    const polygonArcSets = geom.type === 'Polygon' ? [geom.arcs] : geom.arcs;

    polygonArcSets.forEach(polyArcs => {
      const rings = polyArcs.map(ringArcs => decodeTopoRing(topoData, ringArcs));
      const outerMetrics = computeRingMetrics(rings[0]);
      let finalName = baseName;

      if (baseName === '屏東縣' && outerMetrics.centerLng < 120.42 && outerMetrics.centerLat < 22.40) {
        finalName = '小琉球';
      } else if (baseName === '臺東縣' && outerMetrics.centerLng > 121.35) {
        if (outerMetrics.centerLat > 22.50) finalName = '綠島';
        else finalName = '蘭嶼';
      } else if (baseName === '宜蘭縣' && outerMetrics.centerLng > 121.9) {
        finalName = '龜山島';
      }

      if (!regionPolygons[finalName]) regionPolygons[finalName] = [];
      regionPolygons[finalName].push({ rings, metrics: outerMetrics });
    });
  });

  const MAGNIFIED_ISLANDS = ['金門縣', '連江縣', '澎湖縣', '小琉球', '蘭嶼', '綠島', '龜山島'];
  const ISLAND_TARGETS = {
    '金門縣': [120.3, 24.8],
    '連江縣': [120.65, 25.0],
    '澎湖縣': [119.5, 23.6],
    '小琉球': [120.3, 22.2],
    '蘭嶼':   [121.45, 22.1],
    '綠島':   [121.6, 22.8],
    '龜山島': [122.0, 24.8]
  };

  for (const [rName, polys] of Object.entries(regionPolygons)) {
    let validPolys = polys;
    
    if (MAGNIFIED_ISLANDS.includes(rName)) {
      validPolys.sort((a, b) => b.metrics.bboxArea - a.metrics.bboxArea);
      validPolys = [validPolys[0]]; 
    }

    validPolys.forEach(poly => {
      let finalRings = poly.rings;
      let finalMetrics = poly.metrics;

      if (MAGNIFIED_ISLANDS.includes(rName)) {
        const targetCenter = ISLAND_TARGETS[rName];
        const oldCenter = [poly.metrics.centerLng, poly.metrics.centerLat];
        
        const scaleFactor = (rName === '金門縣') ? 1.5 : 3;
        finalRings = transformPolygon(poly.rings, oldCenter, targetCenter, scaleFactor);
        finalMetrics = computeRingMetrics(finalRings[0]);

        const m = finalMetrics;
        const pad = 0.05;
        const bboxRings = [[
          [m.minLng - pad, m.minLat - pad],
          [m.maxLng + pad, m.minLat - pad],
          [m.maxLng + pad, m.maxLat + pad],
          [m.minLng - pad, m.maxLat + pad],
          [m.minLng - pad, m.minLat - pad]
        ]];
        parsedGeoFeatures.push({
          type: 'Feature',
          properties: { name: rName + '_bbox', isBoundingBox: true },
          geometry: { type: 'Polygon', coordinates: bboxRings }
        });
      }

      parsedGeoFeatures.push({
        type: 'Feature',
        properties: { name: rName, color: REGION_PASTEL_COLORS[rName] || '#b4efb2' },
        geometry: { type: 'Polygon', coordinates: finalRings },
        _outerMetrics: finalMetrics
      });

      if (!largestAreaPerRegion[rName] || finalMetrics.bboxArea > largestAreaPerRegion[rName]) {
        largestAreaPerRegion[rName] = finalMetrics.bboxArea;
        regionCentersMap[rName] = [finalMetrics.centerLat, finalMetrics.centerLng];
      }
    });
  }
}

